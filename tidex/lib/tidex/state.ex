defmodule Tidex.State do
  @moduledoc false

  defstruct title: "Tidex",
            project_name: "exmex-talk",
            test_state: :idle,
            server_state: :down,
            test_command: "mix test",
            test_format: :exunit,
            server_command: "python3 -m http.server 4000",
            browser_url: "http://localhost:4000",
            editor_command: "vi",
            output_lines: [],
            output_scroll: :follow,
            output_source: nil,
            test_log: [],
            server_log: [],
            git_log: [],
            test_ref: nil,
            test_pid: nil,
            server_ref: nil,
            server_pid: nil,
            git: %{branch: nil, dirty: 0, untracked: 0, status: ""},
            git_cmd_ref: nil,
            git_cmd_pid: nil,
            overlay: nil,
            modal: nil,
            setup: nil,
            cwd: ".",
            config_path: nil,
            config_root: ".",
            files: %{},
            failures: [],
            failure_index: 0,
            width: 80,
            height: 24

  @type test_status :: :idle | :running | :pass | :fail
  @type server_status :: :up | :down
  @type overlay :: nil | :setup

  @type t :: %__MODULE__{
          title: String.t(),
          project_name: String.t(),
          test_state: test_status(),
          server_state: server_status(),
          test_command: String.t(),
          test_format: :exunit | :minitest | :none,
          server_command: String.t(),
          browser_url: String.t(),
          editor_command: String.t(),
          output_lines: [String.t()],
          output_scroll: Tidex.Scroll.t(),
          output_source: :test | :git | nil,
          test_log: [String.t()],
          server_log: [String.t()],
          git_log: [String.t()],
          test_ref: reference() | nil,
          test_pid: pid() | nil,
          server_ref: reference() | nil,
          server_pid: pid() | nil,
          git: Tidex.Git.snapshot(),
          git_cmd_ref: reference() | nil,
          git_cmd_pid: pid() | nil,
          overlay: overlay(),
          modal: Tidex.Modal.t() | nil,
          setup: Tidex.Setup.t() | nil,
          cwd: String.t(),
          config_path: String.t() | nil,
          config_root: String.t(),
          files: %{optional(1..4) => String.t()},
          failures: [Tidex.Failures.t()],
          failure_index: non_neg_integer(),
          width: pos_integer(),
          height: pos_integer()
        }
end
